import type { InvoiceType } from "./types";

export const LETTER_WIDTH_MM = 215.9;
export const LETTER_HEIGHT_MM = 279.4;
export const MM_TO_PT = 72 / 25.4; // 2.834645669291339
export const PT_TO_MM = 25.4 / 72; // 0.3527777777777778

export function mmToPt(mm: number): number {
  return mm * MM_TO_PT;
}

export function ptToMm(pt: number): number {
  return pt * PT_TO_MM;
}

export type FieldType =
  | "invoiceNumber"
  | "date"
  | "customer"
  | "tin"
  | "address"
  | "terms"
  | "dueDate"
  | "poNumber"
  | "salesRep"
  | "colItem"
  | "colDesc"
  | "colQty"
  | "colUnit"
  | "colAmount"
  | "totalSales"
  | "vat"
  | "net"
  | "wht"
  | "due"
  | "vatableSales"
  | "vatAmount"
  | "refNumber"
  | "pageNumber"
  | "customText";

export type FieldCategory = "header" | "customer" | "items" | "totals" | "custom";

export interface LayoutField {
  id: string;
  name: string;
  type: FieldType;
  category: FieldCategory;
  // Position & Dimensions in millimeters (mm)
  x: number;
  y: number;
  w: number;
  h: number;
  // Styling
  fontSize: number; // in pt
  fontWeight: "normal" | "bold";
  align: "left" | "center" | "right";
  color: string; // hex
  wrapText?: boolean;
  visible: boolean;
  zIndex: number;
  // For custom text/labels
  staticText?: string;
  // Sample text for editor preview
  sampleValue?: string;
}

export interface TableConfig {
  rowTopMm: number;
  rowHeightMm: number;
  rowCount: number;
}

export interface InvoiceLayout {
  id: string;
  name: string;
  invoiceType: InvoiceType;
  paperSize: "letter";
  orientation: "portrait" | "landscape";
  pageWidthMm: number;
  pageHeightMm: number;
  marginsMm: {
    top: number;
    bottom: number;
    left: number;
    right: number;
  };
  showBackgroundTemplate: boolean;
  backgroundOpacity: number; // 0 to 1
  tableConfig: TableConfig;
  fields: LayoutField[];
  createdAt: string;
  updatedAt: string;
}

