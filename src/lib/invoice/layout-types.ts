/** Factory for complete default invoice layout */
export function createDefaultLayout(type: InvoiceType): InvoiceLayout {
  const isCharge = type === "charge";
  return {
    id: `default-${type}`,
    name: isCharge ? "Default Charge Invoice" : "Default Cash Invoice",
    invoiceType: type,
    paperSize: "letter",
    orientation: "portrait",
    pageWidthMm: LETTER_WIDTH_MM,
    pageHeightMm: LETTER_HEIGHT_MM,
    marginsMm: {
      top: 6.0,
      bottom: 6.0,
      left: 6.0,
      right: 6.0,
    },
    showBackgroundTemplate: true,
    backgroundOpacity: 1.0,
    tableConfig: {
      rowTopMm: isCharge ? 81.5 : 86.0,
      rowHeightMm: isCharge ? 6.3 : 6.25,
      rowCount: 10,
    },
    fields: isCharge ? getDefaultChargeFields() : getDefaultCashFields(),
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}
